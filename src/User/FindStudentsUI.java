    // Convert DLL to Array
    private Student[] toArray(DoublyLinkedList list) {

        int count = 0;
        Link current = list.getFirst();

        // count nodes
        while (current != null) {
            count++;
            current = current.next;
        }

        Student[] arr = new Student[count];

        current = list.getFirst();
        int i = 0;

        while (current != null) {

            arr[i++] = new Student(
                    current.studentId,
                    current.name,
                    current.age,
                    current.courseEnrolled,
                    current.level,
                    current.timestamp
            );

            current = current.next;
        }

        return arr;
    }

