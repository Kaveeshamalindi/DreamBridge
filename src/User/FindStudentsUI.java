    private void btnFindActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnFindActionPerformed
        // TODO add your handling code here:
        String input = javax.swing.JOptionPane.showInputDialog("Enter Student ID:");

        if (input == null) return;

        //Create an empty DLL
        DoublyLinkedList list = new DoublyLinkedList();

        // Load file 
        StudentFileDB.loadStudents(list);

        // Convert DLL to Array
        Student[] arr = toArray(list);

        // Sort manually using QuickSort
        QuickSortStudents.quickSort(arr, 0, arr.length - 1);

        // Call the Binary search
        Student result = BinarySearch.search(arr, input);

        if (result != null) {

            String msg = "Student Found!\n\n"
                    + "ID: " + result.getStudentId() + "\n"
                    + "Name: " + result.getName() + "\n"
                    + "Age: " + result.getAge() + "\n"
                    + "Course: " + result.getCourseEnrolled() + "\n"
                    + "Level: " + result.getLevel() + "\n"
                    + "Timestamp: " + result.getTimestamp();

            JOptionPane.showMessageDialog(this, msg);
            txtArea.setText(msg);

        } else {
            JOptionPane.showMessageDialog(this, "Student not found!");
            txtArea.setText("Not Found !");
        }
    }//GEN-LAST:event_btnFindActionPerformed

