    private void btnDisplayActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDisplayActionPerformed
        // TO Display Button Option
        
        // load from file to DLL
        sfDB.loadToMemory(); 

        tblModel.setRowCount(0);

        DoublyLinkedList list = sfDB.getDLL();
        Link current = list.getFirst();

        while (current != null) {

            tblModel.addRow(new Object[]{
                current.studentId,
                current.name,
                current.age,
                current.courseEnrolled,
                current.level,
                current.timestamp
            });

            current = current.next;
        }
    }//GEN-LAST:event_btnDisplayActionPerformed

    private void btnCheckOutActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCheckOutActionPerformed
        // TO Enroll Button Option
        try {
            String id = JOptionPane.showInputDialog("Enter Student ID");

            if (!sfDB.deleteStudent(id)) {
                throw new Exception("Student not found!");
            }

            JOptionPane.showMessageDialog(rootPane, "Student is successfully Enrolled!");

        } catch (Exception e) {
            JOptionPane.showMessageDialog(rootPane,
                    e.getMessage(),
                    "Error",
                    JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnCheckOutActionPerformed

