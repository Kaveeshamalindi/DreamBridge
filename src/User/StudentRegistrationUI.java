    private void btnDisplayActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDisplayActionPerformed
        //To Display Button Option
        DefaultTableModel model = (DefaultTableModel) SRTable.getModel();

        model.setRowCount(0);

        Link current = list.getFirst();

        while(current != null){

            model.addRow(new Object[]{
                current.studentId,
                current.name,
                current.age,
                current.courseEnrolled,
                current.level,
                current.timestamp
            });

            current = current.next;
        }
    }//GEN-LAST:event_btnDisplayActionPerformed

    private void btnRegistorActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnRegistorActionPerformed
        //To Registor Button Option
        if (checkVal()){

            try {
                String StudentID = txtStdID.getText();

                // Check Duplicate Student ID
                if (list.DuplicateStudentID(StudentID)) {
                    JOptionPane.showMessageDialog(this, "Student ID already exists!");
                    txtStdID.setText("");
                    txtName.setText("");
                    txtAge.setText("");
                    rdoSenior.setSelected(false);
                    rdoJunior.setSelected(false);
                    rdoFresher.setSelected(false);
                    txtTimestamp.setText("");
                    return;
                }

                String Name = txtName.getText();

                int Age;

                try {
                    Age = Integer.parseInt(txtAge.getText());
                } catch (NumberFormatException e) {
                    JOptionPane.showMessageDialog(this, "Invalid Age!");
                    return;
                }

                String Course = cmbCourse.getSelectedItem().toString();

                String Level="";
                if(rdoFresher.isSelected()) {
                    Level="Fresher";
                } else if (rdoJunior.isSelected()){
                    Level="Junior";
                } else if (rdoSenior.isSelected()) {
                    Level = "Senior";
                } else {
                    JOptionPane.showMessageDialog(this, "Please select Student Level");
                    return;
                }

                String Timestamp = txtTimestamp.getText();

                //Data insert at the end of DDL
                list.insertLast(StudentID, Name, Age, Course, Level, Timestamp);
                
                //Data save into the file
                StudentFileDB.saveStudent(StudentID, Name, Age, Course, Level, Timestamp);

                JOptionPane.showMessageDialog(this, "Data Inserted Successfully!");

                txtStdID.setText("");
                txtName.setText("");
                txtAge.setText("");
                cmbCourse.setSelectedIndex(-1);
                txtTimestamp.setText("");
                rdoSenior.setSelected(false);
                rdoJunior.setSelected(false);
                rdoFresher.setSelected(false);

            } catch (NumberFormatException e) {
                txtStdID.setText("");
                txtName.setText("");
                txtAge.setText("");
                cmbCourse.setSelectedIndex(-1);
                txtTimestamp.setText("");
                rdoSenior.setSelected(false);
                rdoJunior.setSelected(false);
                rdoFresher.setSelected(false);
            }
        }
    }//GEN-LAST:event_btnRegistorActionPerformed

