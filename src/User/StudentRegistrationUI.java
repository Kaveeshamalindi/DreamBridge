    private boolean checkVal(){
        
        if (txtStdID.getText().equals("")){
            JOptionPane.showMessageDialog(this, "Student ID cannot be blank");
            return false;
        }
        if (txtName.getText().equals("")){
            JOptionPane.showMessageDialog(this, "Name cannot be blank");
            return false;
        }
        if (txtAge.getText().equals("")){
            JOptionPane.showMessageDialog(this, "Age cannot be blank");
            return false;
        }
        if (txtTimestamp.getText().equals("")) {
            JOptionPane.showMessageDialog(this, "Enrollment Timestamp cannot be blank");
            return false;
        }
        return true;
    }

