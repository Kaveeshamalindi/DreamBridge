    private void btnDisplayActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDisplayActionPerformed
        // TO Display Button Option
        DefaultTableModel model = (DefaultTableModel) EMTable.getModel();
        model.setRowCount(0); // clear table

        try {
            // Read File  
            BufferedReader br = new BufferedReader(new FileReader("StudentRegistration.txt"));
            String line;
            //int arrival = 0;
            
            
            pq = new PriorityQ(100);   // reset queue
            int arrival = 0;           // reset arrival

            while ((line = br.readLine()) != null) {

                String[] data = line.split(",");

                try {
                    String StudentID = data[0];
                    String Name = data[1];
                    int Age = Integer.parseInt(data[2]);
                    String Course = data[3];
                    String Level = data[4];
                    String Timestamp = data[5];

                    Student p = new Student(StudentID, Name, Age, Course, Level, Timestamp, arrival++);

                    // Insert into the Priority Queue 
                    pq.insert(p);

                } catch (Exception e) {
                    System.out.println("Skipping invalid: " + line);
                }
            }

            br.close();

            //Display
            while (!pq.isEmpty()) {
                Student p = pq.remove();

                model.addRow(new Object[]{
                    p.getStudentId(),
                    p.getName(),
                    p.getAge(),
                    p.getCourseEnrolled(),
                    p.getLevel(),
                    p.getTimestamp(),
                });
            }

        } catch (Exception e) {
            e.printStackTrace();
        }
    }//GEN-LAST:event_btnDisplayActionPerformed

